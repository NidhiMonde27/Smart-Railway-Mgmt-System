-- ======================================================================
-- SUPABASE MIGRATION SCRIPT FOR APLI-MUMBAI SMART RAILWAY SYSTEM
-- Features: Season Tickets, Counter Tickets, Via Routes, Coach Occupancy & Platform Scanner Events
-- ======================================================================

-- 1. Create / Update Tickets Table
create table if not exists tickets (
  id uuid default gen_random_uuid() primary key,
  ticket_id text not null unique,
  category text default 'journey', -- 'journey', 'season', 'counter'
  source_type text default 'online', -- 'online', 'counter'
  season_type text, -- 'monthly', 'quarterly', 'yearly'
  source text not null,
  destination text not null,
  via text default 'Direct',
  class text not null,
  ticket_type text not null,
  passengers int default 1,
  fare numeric default 0,
  issued_at timestamp with time zone default timezone('utc'::text, now()),
  valid_from timestamp with time zone,
  valid_upto timestamp with time zone,
  used boolean default false,
  status text default 'Active',
  user_id text,
  created_at timestamp with time zone default timezone('utc'::text, now())
);

-- 2. Create Train Coaches Table for Coach-Wise Crowd Estimation
create table if not exists train_coaches (
  id bigint generated by default as identity primary key,
  train_id text not null,
  coach_number text not null, -- C1 to C12
  passengers int default 0,
  capacity int default 150,
  occupancy_pct int default 0,
  updated_at timestamp with time zone default timezone('utc'::text, now()),
  unique(train_id, coach_number)
);

-- 3. Create Scanner Events Table for Platform Gate Logging
create table if not exists scanner_events (
  id bigint generated by default as identity primary key,
  train_id text not null,
  station text not null,
  scanner_zone text not null check (scanner_zone in ('START', 'MIDDLE', 'END')),
  event_type text not null check (event_type in ('ENTRY', 'EXIT')),
  passenger_count int default 1,
  ticket_id text,
  created_at timestamp with time zone default timezone('utc'::text, now())
);
