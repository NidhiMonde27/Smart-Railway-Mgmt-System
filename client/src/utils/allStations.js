/**
 * Returns all applicable line names for a given station (handles shared / interchange stations)
 * @param {string} stationName 
 * @returns {Array<string>} List of line names (e.g. ["Central", "Western"])
 */
export const getStationLines = (stationName) => {
  if (!stationName) return [];
  const sName = stationName.trim().toLowerCase();

  const lines = new Set();
  const allStns = getAllStations();
  allStns.forEach((s) => {
    if (s.name.toLowerCase() === sName) {
      lines.add(s.line);
    }
  });

  // Interchange / shared mappings override to ensure complete labels
  if (sName === "dadar") { lines.add("Central"); lines.add("Western"); }
  if (sName === "csmt" || sName === "masjid" || sName === "sandhurst road" || sName === "kurla") { lines.add("Central"); lines.add("Harbour"); }
  if (["mahim", "bandra", "khar road", "santacruz", "vile parle", "andheri", "jogeshwari", "ram mandir", "goregaon"].includes(sName)) { lines.add("Harbour"); lines.add("Western"); }
  if (sName === "thane") { lines.add("Central"); lines.add("Trans-Harbour"); }
  if (["vashi", "sanpada", "juinagar", "nerul"].includes(sName)) { lines.add("Harbour"); lines.add("Trans-Harbour"); }

  return Array.from(lines);
};

/**
 * Formats a display label indicating line affiliation for interchange transparency
 * e.g., "Andheri — Harbour / Western"
 * @param {string} stationName 
 * @returns {string}
 */
export const getStationDisplayLabel = (stationName) => {
  if (!stationName) return "";
  const lines = getStationLines(stationName);
  if (lines.length > 1) {
    return `${stationName} — ${lines.join(" / ")}`;
  } else if (lines.length === 1) {
    return `${stationName} (${lines[0]})`;
  }
  return stationName;
};

